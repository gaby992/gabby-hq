// The human guide to the bot, from ONE source: comandos.json. It becomes
// docs/comandos.md (`npm run comandos`) and the 2–3 Telegram messages of
// "/ayuda todo". Edit the JSON, never the two outputs.

import guia from './comandos.json'
import { escapeHtml } from './telegram'

export interface LineaGuia {
  ejemplo: string
  que: string
}

export interface SeccionGuia {
  id: string
  emoji: string
  titulo: string
  lineas: LineaGuia[]
}

export const GUIA: { intro: string; secciones: SeccionGuia[] } = guia

/** How the sections are split across Telegram messages (at most 3). */
const PARTES: string[][] = [['ver', 'agregar'], ['actuar', 'varias'], ['otros']]

function seccionHtml(s: SeccionGuia): string {
  return [
    `${s.emoji} <b>${escapeHtml(s.titulo).toUpperCase()}</b>`,
    ...s.lineas.map((l) => `<code>${escapeHtml(l.ejemplo)}</code> — ${escapeHtml(l.que)}`),
  ].join('\n')
}

/** "/ayuda todo": the guide as Telegram HTML, one string per message. */
export function guiaTelegram(): string[] {
  const porId = new Map(GUIA.secciones.map((s) => [s.id, s]))
  return PARTES.map((ids, i) => {
    const bloques = ids.map((id) => porId.get(id)).filter((s): s is SeccionGuia => !!s).map(seccionHtml)
    const cabecera = i === 0 ? `📖 <b>Guía del asistente</b> (${i + 1}/${PARTES.length})\n${escapeHtml(GUIA.intro)}` : `📖 (${i + 1}/${PARTES.length})`
    return [cabecera, ...bloques].join('\n\n')
  })
}

/** docs/comandos.md, regenerated by scripts/comandos-md.mjs. */
export function guiaMarkdown(): string {
  const out: string[] = [
    '# GabbyHQ — Chuleta del bot de Telegram',
    '',
    '> Generado desde `src/lib/asistente/comandos.json` con `npm run comandos`. No editar a mano.',
    '',
    GUIA.intro,
    '',
    'Es lo mismo que manda el bot con `/ayuda todo`. La guía técnica está en [asistente.md](asistente.md).',
    '',
  ]
  for (const s of GUIA.secciones) {
    out.push(`## ${s.emoji} ${s.titulo}`, '')
    for (const l of s.lineas) out.push(`- \`${l.ejemplo}\` — ${l.que}`)
    out.push('')
  }
  return out.join('\n')
}
